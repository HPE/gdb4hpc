#!/usr/bin/env python3

import sys
import datetime
import os
import io

import lib

if len(sys.argv) < 5:
    print(f"usage: {sys.argv[0]} <input md> <input config.h> <output h> <output cpp>")
    exit(-1)

md_path = sys.argv[1]
config_path = sys.argv[2]
output_h_path = sys.argv[3]
output_cpp_path = sys.argv[4]

config = lib.get_config_dict(config_path)

class HelpText():
    def __init__(self, name, text):
        self.name = name
        self.text = text

    def output_h(self, output):
        output.write(f"extern const char* const {self.name}[];\n")

    def output_cpp(self, output):
        b = "{"
        output.write(f"const char* const {self.name}[] = {b}\n")
        for line in self.text.split("\n"):
            line = line.rstrip()

            output.write(f"    \"{line.rstrip()}\",\n")
        output.write("    0};\n\n")

class Parser():
    def __init__(self, blob, config):
        self.blob = blob
        self.config = config

    def find_end_of_section(self):
        title_start = self.blob.find("##")
        end = self.blob.find("##", title_start + 2)
        if end == -1:
            end = len(self.blob)
        return end

    def parse_next(self) -> HelpText:
        title_start = self.blob.find("##")
        if title_start == -1:
            return None

        name_start = self.blob.find("`", title_start) + 1
        name_end = self.blob.find("`", name_start)
        name = self.blob[name_start : name_end]

        text_start = self.blob.find("\n", title_start) + 1
        text_end = self.find_end_of_section()
        text = self.blob[text_start : text_end]

        self.blob = self.blob[text_end:]

        # filter out commonmark line breaks
        # https://spec.commonmark.org/0.31.2/#hard-line-breaks
        text = text.replace("\\\n", "\n")

        # escape backslashes in the text
        text = text.replace("\\", "\\\\")

        # escape quotes
        text = text.replace('"', '\\\"')

        text = text.strip()

        text = lib.apply_config(self.config, text)

        return HelpText(name, text)

parser = Parser(open(md_path, "r").read(), config)

blurb = f"""// Copyright {str(datetime.datetime.now().year)} Hewlett Packard Enterprise Development LP.
//
// don't edit this file by hand!
// this file is auto generated by generate_help_source.py from the contents of help.md.
// edit help.md with your favorite text editor and then rebuild gdb4hpc with meson.
"""

old_output_h_content = None
if os.path.isfile(output_h_path):
    old_output_h_content = open(output_h_path).read()

output_h = io.StringIO()
output_h.write(blurb)
output_h.write("\n")
output_h.write("#pragma once\n")
output_h.write("\n")

output_cpp = open(output_cpp_path, "w")
output_cpp.write(blurb)
output_cpp.write("\n")
output_cpp.write(f"#include \"{os.path.basename(output_h_path)}\"\n")
output_cpp.write("\n")

help = parser.parse_next()
while help is not None:
    help.output_h(output_h)
    help.output_cpp(output_cpp)
    help = parser.parse_next()

dummy = HelpText("dummy_help", "")
dummy.output_h(output_h)
dummy.output_cpp(output_cpp)

# some extra logic to be smart about emitting the header - if we emit a changed header,
# some ~40 files need to be rebuilt (almost all the cmd_*.cpp files). but most often, it's
# not the header that changes, but the .cpp file, so we can save a lot of time here with a simple check
output_h_str = output_h.getvalue()
if old_output_h_content == None or old_output_h_content != output_h_str:
    output_h_file = open(output_h_path, "w")
    output_h_file.write(output_h_str)
