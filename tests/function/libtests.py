# generate an error message        
def error(message, line_num, line):
    return (False, message + " at " + str(line_num) + " on " + line)

def compare_files(ref_file_path, out_file_path):
    ref_conn = ''
    launching = False

    global suppressedCheck; suppressedCheck.clear()

    with open(ref_file_path, "r") as ref, open(out_file_path) as out:
        outline_num = 0
        for outline in out:
            outline_num += 1
            orig_outline = outline.rstrip()
            outline = anonymize_line(orig_outline)

            # notice app launches
            if outline == "Starting application, please wait...":
                launching = True

            # input line for the batch file
            out_batch_line = is_batch(outline)
            if out_batch_line != None:
                if launching:
                    # found next command before launching completed. launch probably failed.
                    return error("launch never completed", outline_num, orig_outline)

                refline = next_ref_line(ref)
                global indeterminate; indeterminate = False
                if refline == None:
                    return error("extra output", outline_num, orig_outline)
    
                cmp = compare_batch_lines(refline, out_batch_line)
                if cmp:
                    return error(cmp, outline_num, orig_outline)
                continue
            
            if launching:
                # mrnet and zmqnet output differ, so ignore launch output 
                # until "Launch complete." or another command (checked above)
                if outline == "Launch complete.":
                    launching = False
                    indeterminate = False # XXX: next_ref_line would skip "Launch
                                          #      complete." line otherwise

                    # fast forward ref file until it catches up
                    refline = next_ref_line(ref)
                    while refline is not None and refline != "Launch complete.":
                        refline = next_ref_line(ref)
                    if refline is None:
                        return error("extra output", outline_num, orig_outline)
                continue

            if indeterminate:
                continue

            # gdb procset based output
            proc = is_procset(outline)
            if proc:
                if not procRefs.get(proc):
                    procRefs[proc] = []
                matched = False
                procIdx = 0
                while not matched:
                    while procIdx >= len(procRefs[proc]):
                        refline = next_ref_line(ref)
                        if refline == None:
                            return error("extra output", outline_num, orig_outline)
                        rproc = is_procset(refline)
                        if rproc:
                            if procRefs.get(rproc) == None:
                                procRefs[rproc] = []
                            procRefs[rproc].append([refline, ""])
                        else:
                            return error("did not find match", outline_num, orig_outline)

                    refline, seen = procRefs[proc][procIdx]
                    cmp, newref, seen = compare_procset_lines(refline, outline, seen)
                    if cmp is not None and cmp == False:
                        procIdx += 1
                    elif cmp is not None and cmp == True:
                        procRefs[proc].pop(procIdx)
                        matched = True
                    else:
                        procRefs[proc][procIdx][0] = newref
                        procRefs[proc][procIdx][1] = seen
                        matched = True
                if not matched:
                    return error("mismatch in return", outline_num, orig_outline)
                continue

            # output printed by the application itself
            prog_out = is_prog_out(outline)
            if prog_out:
                continue

            # other output
            refline = next_ref_line(ref)
            if refline == None:
                return error("extra output", outline_num, orig_outline)
            if not compare_non_procset_lines(refline, outline):
                return error("mismatch", outline_num, orig_outline)

        # make sure every line in the ref file has been accounted for
        extra = next_ref_line(ref)
        if extra != None:
            return (False, f"output ended before match for \"{extra}\"")

    return (True, ' ')

# check an .out file for a test and return true if all of its attempted launches succeeded.
def all_launches_successful(outfile):
    # Check that every "Starting application, please wait..." has a
    # matching "Launch Complete."
    with open(outfile) as out:
        currently_launching = False
        for line in out.readlines():
            line = line.strip()
            if line == "Starting application, please wait...":
                if not currently_launching:
                    currently_launching = True
                else:
                    # Shouldn't encounter another launch before a previous one completed
                    return False

            if line == "Launch complete.":
                if currently_launching:
                    currently_launching = False
                else:
                    # Shouldn't find "Launch Complete." unless we launched something
                    return False

        return currently_launching == False

    # shouldn't ever get here? failed to open the file?
    return False

def convert_slurm_launcher_args(num_ranks: int, slurm_args: str, output_wlm: str):
    """
    convert `slurm_args` launcher args to launcher args of the same meaning for
    `output_wlm`. `output_wlm` should be a string returned from detect_wlm.

    for example, in slurm, "-n4 -N1" means "four ranks on one node", but on
    alps it means "four ranks, one on each node, totaling four nodes".
    convert_slurm_launcher_args(4, "-N1", "ALPS") would output "-N4".

    this function is not fully featured and only converts *some* arguments to
    *some* wlms.  conversions are implemented based on needs of existing tests.
    see the unit test for an idea of what's implemented.
    """

    if output_wlm == "SLURM":
        return slurm_args

    args = slurm_args.split()

    if output_wlm == "ALPS":
        # convert -n4 -N1 combo to -n4 -N4
        nodes = None # (idx, value)
        for i, arg in enumerate(args):
            if arg.startswith("-N"):
                # this does not support the form with spaces ("-N 4")
                nodes = (i, int(arg[2:]))

        if nodes:
            args[nodes[0]] = f"-N{math.ceil(num_ranks / nodes[1])}"

    return " ".join(args)

